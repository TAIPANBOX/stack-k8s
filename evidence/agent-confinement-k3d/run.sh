#!/usr/bin/env bash
# The agent-pod network on a live k3d cluster (CLAUDE.md invariant 77). Run from the repository root on a machine with
# docker, k3d and kubectl; the run uses its own kubeconfig file and never touches ~/.kube/config.
#
#   evidence/agent-confinement-k3d/run.sh | tee evidence/agent-confinement-k3d/output.txt
#
# What is real: manifests/30-network-policy.yaml and manifests/58-agent-tokens-network.yaml, and every other
# NetworkPolicy of the default apply set (manifests/54-delegation.yaml among them), applied as the product has them,
# and agent-tokens/confine-check.sh with the overlay agent-tokens/confined-agent, run as an operator runs them.
# What is a stand-in: the stack's own pods. Each is a busybox pod generated by standins.py from the rendered manifests,
# with the real pod labels and the real container ports, answering HTTP. No stack image runs here.
#
# The run, in order: the check against the policies as shipped (must pass), then four faults the check must catch (the
# agent-pod policy widened to all egress, the namespace's egress isolation stripped from default-deny and allow-dns, the
# agent-pod policy too narrow, the agent-pod policy deleted) and one change it must not call a fault (default-deny
# stripped alone), then the shipped policies again (must pass). NO_ENFORCE=1 is the other run: a cluster whose
# NetworkPolicy controller is off, where the check must go red.
# It deletes the cluster and the work directory on every exit path.
set -uo pipefail

cd "$(dirname "$0")/../.."
HERE=evidence/agent-confinement-k3d
CLUSTER="${CLUSTER:-g23-confine}"
API_PORT="${API_PORT:-6551}"
EXTERNAL="${EXTERNAL:-1.1.1.1:443}"
WORK="$(mktemp -d)"
export KUBECONFIG="$WORK/kubeconfig"
problems=0

cleanup() {
  if [ "${KEEP_CLUSTER:-}" = 1 ]; then
    printf 'kept for inspection: KUBECONFIG=%s, remove with k3d cluster delete %s\n' "$KUBECONFIG" "$CLUSTER"
    return
  fi
  k3d cluster delete "$CLUSTER" >/dev/null 2>&1
  rm -rf "$WORK"
}
trap cleanup EXIT

say() { printf '\n== %s\n' "$*"; }
die() { printf 'ABORT: %s\n' "$*"; exit 2; }
want_exit() { # want got what
  if [ "$1" = "$2" ]; then printf '   exit %s, as expected: %s\n' "$2" "$3"; else printf '   exit %s, expected %s: %s\n' "$2" "$1" "$3"; problems=$((problems + 1)); fi
}

say "tools"
k3d version
kubectl version --client
docker version --format 'docker server {{.Server.Version}}'
say "files under test (sha256: compare with git show <commit>:<path> | sha256sum)"
sha256sum manifests/30-network-policy.yaml manifests/58-agent-tokens-network.yaml agent-tokens/confine-check.sh \
  agent-tokens/confined-agent/agent.yaml agent-tokens/confined-agent/kustomization.yaml \
  evidence/agent-confinement-k3d/run.sh evidence/agent-confinement-k3d/standins.py

say "cluster $CLUSTER (k3d, one server, no load balancer, API on 127.0.0.1:$API_PORT, its own kubeconfig)"
k3d cluster list "$CLUSTER" >/dev/null 2>&1 && die "a k3d cluster named $CLUSTER already exists; this run does not touch it"
# NO_ENFORCE=1 starts k3s with its embedded NetworkPolicy controller off: the control for "does the check notice a cluster
# that enforces nothing".
EXTRA=""
[ "${NO_ENFORCE:-}" = 1 ] && EXTRA="--k3s-arg --disable-network-policy@server:*"
# shellcheck disable=SC2086
k3d cluster create "$CLUSTER" --servers 1 --agents 0 --no-lb --api-port "127.0.0.1:$API_PORT" $EXTRA \
  --kubeconfig-update-default=false --kubeconfig-switch-context=false --wait --timeout 300s >/dev/null || die "k3d cluster create failed"
k3d kubeconfig get "$CLUSTER" > "$KUBECONFIG" || die "no kubeconfig"
kubectl get nodes -o wide
# k3s writes its packaged coredns a few seconds after the node is Ready; wait for the object before waiting on its rollout.
for _ in $(seq 1 90); do kubectl -n kube-system get deployment coredns >/dev/null 2>&1 && break; sleep 2; done
kubectl -n kube-system rollout status deployment/coredns --timeout=180s || die "coredns did not become ready"

say "namespace agent-stack, as manifests/00-base.yaml declares it (Pod Security restricted)"
python3 - "$WORK" <<'PY' || die "could not read the namespace from manifests/00-base.yaml"
import re, sys
text = open("manifests/00-base.yaml").read()
doc = re.split(r"\n---\s*\n", text)[0]
assert "kind: Namespace" in doc and "name: agent-stack" in doc, doc
open(sys.argv[1] + "/ns.yaml", "w").write(doc + "\n")
PY
kubectl apply -f "$WORK/ns.yaml" || die "namespace"

say "the rendered default apply set, converted to JSON (kubectl kustomize manifests/)"
kubectl kustomize manifests/ | kubectl create --dry-run=client -o json -f - > "$WORK/rendered.json" || die "could not render manifests/"
python3 "$HERE/standins.py" --policies < "$WORK/rendered.json" > "$WORK/policies.json" || die "could not split the rendered set"

say "the NetworkPolicies of the default apply set, applied as the product has them"
kubectl apply -f "$WORK/policies.json" >/dev/null || die "policies"
kubectl -n agent-stack get networkpolicy

say "stand-ins for the stack's own pods, generated from the rendered manifests (real labels, real container ports)"
python3 "$HERE/standins.py" < "$WORK/rendered.json" > "$WORK/standins.json" || die "standins.py"
kubectl apply -f "$WORK/standins.json" >/dev/null || die "stand-ins"
kubectl -n agent-stack wait --for=condition=Ready pod --all --timeout=240s >/dev/null || die "stand-ins did not become ready"
kubectl -n agent-stack get pods -L plane,app --no-headers | awk '{printf "   %-28s %-8s plane=%s app=%s\n", $1, $3, $6, $7}'

run_check() { # label
  say "$1"
  ./agent-tokens/confine-check.sh --external "$EXTERNAL"
  return $?
}

if [ "${STOP_AFTER_SETUP:-}" = 1 ]; then printf 'setup done\n'; exit 0; fi

if [ "${NO_ENFORCE:-}" = 1 ]; then
  run_check "run: the check on a cluster whose NetworkPolicy controller is off (k3s --disable-network-policy)"
  want_exit 1 $? "the check must go red: the objects exist and nothing enforces them"
  say "result"
  if [ "$problems" -eq 0 ]; then printf 'RUN_EXIT=0 (every run ended as expected)\n'; else printf 'RUN_EXIT=1 (%d runs did not end as expected)\n' "$problems"; fi
  [ "$problems" -eq 0 ]
  exit $?
fi

run_check "run 1: agent-tokens/confine-check.sh, policies as shipped"
want_exit 0 $? "every row as expected"

say "fault A: the agent-pod egress policy widened to all egress (a rule that names no peer)"
kubectl -n agent-stack apply -f - >/dev/null <<'YAML'
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: agent-token-pods-egress
  namespace: agent-stack
spec:
  podSelector: { matchLabels: { taipanbox.dev/agent-token: "true" } }
  policyTypes: ["Egress"]
  egress:
    - {}
YAML
run_check "run 2: the same check against the widened policy"
want_exit 1 $? "the check must go red"
kubectl apply -f "$WORK/policies.json" >/dev/null || die "restore policies"

say "not a fault: default-deny stripped of its Egress type. allow-dns also selects every pod for egress, so a pod stays isolated"
kubectl -n agent-stack apply -f - >/dev/null <<'YAML'
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: default-deny
  namespace: agent-stack
spec:
  podSelector: {}
  policyTypes: ["Ingress"]
YAML
run_check "run 3: the check with default-deny on ingress only"
want_exit 0 $? "every row still as expected: allow-dns isolates every pod for egress as well"
kubectl apply -f "$WORK/policies.json" >/dev/null || die "restore policies"

say "fault B: default-deny and allow-dns both stripped of their Egress type, so a pod with no label is not isolated"
kubectl -n agent-stack apply -f - >/dev/null <<'YAML'
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: default-deny
  namespace: agent-stack
spec:
  podSelector: {}
  policyTypes: ["Ingress"]
---
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: allow-dns
  namespace: agent-stack
spec:
  podSelector: {}
  policyTypes: ["Ingress"]
YAML
run_check "run 4: the same check with no policy isolating the namespace's pods for egress"
want_exit 1 $? "the check must go red"
kubectl apply -f "$WORK/policies.json" >/dev/null || die "restore policies"

say "fault C: the agent-pod policy lacks its gateway rule (too narrow: an agent could not call the model)"
kubectl -n agent-stack apply -f - >/dev/null <<'YAML'
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: agent-token-pods-egress
  namespace: agent-stack
spec:
  podSelector: { matchLabels: { taipanbox.dev/agent-token: "true" } }
  policyTypes: ["Egress"]
  egress:
    - to:
        - podSelector: { matchLabels: { app: vouchryx } }
      ports:
        - { protocol: TCP, port: 4310 }
YAML
run_check "run 5: the same check against the narrowed policy"
want_exit 1 $? "the check must go red"
kubectl apply -f "$WORK/policies.json" >/dev/null || die "restore policies"

say "fault D: the agent-pod policy deleted"
kubectl -n agent-stack delete networkpolicy agent-token-pods-egress >/dev/null || die "delete the agent-pod policy"
run_check "run 6: the same check without the agent-pod policy"
want_exit 1 $? "the check must go red, and name the missing policy"
kubectl apply -f "$WORK/policies.json" >/dev/null || die "restore policies"

run_check "run 7: policies as shipped again (the second run is the real test)"
want_exit 0 $? "every row as expected"

say "leftovers of the check in the cluster"
kubectl get namespace agent-confine-scratch 2>&1 | head -1
kubectl -n agent-stack get pod,deployment -l app=agent-confined --no-headers 2>&1 | head -3

say "result"
if [ "$problems" -eq 0 ]; then printf 'RUN_EXIT=0 (every run ended as expected)\n'; else printf 'RUN_EXIT=1 (%d runs did not end as expected)\n' "$problems"; fi
[ "$problems" -eq 0 ]
